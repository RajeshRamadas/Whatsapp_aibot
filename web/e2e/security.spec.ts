function otp(secret: string, seconds: number) {
  let value = 0, bits = 0; const bytes: number[] = [];
  for (const char of secret) { value = (value << 5) | 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'.indexOf(char); bits += 5; if (bits >= 8) { bits -= 8; bytes.push((value >>> bits) & 255); } }
  const count = Buffer.alloc(8); count.writeBigUInt64BE(BigInt(Math.floor(seconds / 30)));
  const hash = createHmac('sha1', Buffer.from(bytes)).update(count).digest(), offset = hash[19] & 15;
  return String((hash.readUInt32BE(offset) & 0x7fffffff) % 1000000).padStart(6, '0');
}
