import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('cloud knowledge: selected Notion pages, Drive consent, refresh, pause and removal', async ({ page }) => {
  test.setTimeout(90000); page.setDefaultTimeout(15000);
  const login = (email: string) => page.request.post('/api/backend/auth/login', { data: { email, password: 'knowledge-sync-browser-passphrase' } });
  expect((await login('knowledge-sync@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/knowledge?view=sync');
  const panel = page.getByRole('region', { name: 'Drive and Notion sync', exact: true });
  await expect(panel.getByText('No cloud knowledge connected yet.', { exact: true })).toBeVisible();
  await panel.getByLabel('Connection name', { exact: true }).fill('Notion policies');
  await panel.getByLabel('Notion page IDs (one per line)', { exact: true }).fill('11111111-1111-4111-8111-111111111111');
  await panel.getByLabel('Notion connection token', { exact: true }).fill('browser-notion-token');
  await panel.getByLabel('This Notion connection has Read content permission only.', { exact: true }).check();
  await panel.getByRole('button', { name: 'Connect Notion', exact: true }).click();
  const notion = page.getByRole('region', { name: 'Notion policies', exact: true });
  await notion.getByRole('button', { name: 'Sync knowledge now', exact: true }).click();
  await expect(notion.getByText('Imported documents: 1', { exact: true })).toBeVisible();
  await expect(notion.getByText('Refund policy.md · Ready', { exact: true })).toBeVisible();
  await notion.getByRole('button', { name: 'Pause knowledge sync', exact: true }).click();
  await expect(notion.getByText('Knowledge paused', { exact: true })).toBeVisible();
  await notion.getByRole('button', { name: 'Resume knowledge sync', exact: true }).click();
  await expect(notion.getByText('Up to date', { exact: true })).toBeVisible();
  const csrf = (await page.context().cookies()).find(c => c.name === 'chatbot_csrf')!.value;
  expect((await page.request.post('/api/backend/_test/knowledge-sync', { headers: { 'X-CSRF-Token': csrf }, data: { removed: true } })).ok()).toBe(true);
  await notion.getByRole('button', { name: 'Sync knowledge now', exact: true }).click();
  await expect(notion.getByText('Imported documents: 0', { exact: true })).toBeVisible();
  page.once('dialog', d => d.accept()); await notion.getByRole('button', { name: 'Disconnect knowledge', exact: true }).click();
  await expect(notion).toHaveCount(0);
  expect((await page.request.post('/api/backend/_test/knowledge-sync', { headers: { 'X-CSRF-Token': csrf }, data: { removed: false } })).ok()).toBe(true);
  await panel.getByRole('combobox', { name: 'Knowledge provider', exact: true }).selectOption('drive');
  await panel.getByLabel('Connection name', { exact: true }).fill('Drive policies');
  await panel.getByLabel('Drive folder IDs (one per line)', { exact: true }).fill('rootfolder123');
  await page.route('https://accounts.google.com/**', route => {
    const state = new URL(route.request().url()).searchParams.get('state');
    return route.fulfill({ status: 302, headers: { Location: 'http://localhost:3000/api/backend/knowledge-sync/callback?state=' + state + '&code=browser-code' } });
  });
  await panel.getByRole('button', { name: 'Authorize Google Drive', exact: true }).click();
  const drive = page.getByRole('region', { name: 'Drive policies', exact: true });
  await drive.getByRole('button', { name: 'Sync knowledge now', exact: true }).click();
  await expect(drive.getByText('Drive policy.md · Ready', { exact: true })).toBeVisible();
  const metadata = await (await page.request.get('/api/backend/knowledge-sync')).json();
  expect(JSON.stringify(metadata)).not.toContain('browser-drive-access');
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Drive और Notion सिंक', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Drive and Notion sync', exact: true })).toBeVisible();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 1100 }); await page.mouse.move(0, 0);
  await page.screenshot({ path: '../docs/screenshots/t10-7-knowledge-sync.png', fullPage: true });
  page.once('dialog', d => d.accept()); await drive.getByRole('button', { name: 'Disconnect knowledge', exact: true }).click();
  await expect(drive).toHaveCount(0);
  await page.context().clearCookies(); expect((await login('knowledge-reader@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/knowledge?view=sync');
  await expect(page.getByRole('button', { name: 'Drive and Notion sync', exact: true })).toHaveCount(0);
  expect((await page.request.get('/api/backend/knowledge-sync')).status()).toBe(403);
});
