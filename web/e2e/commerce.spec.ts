import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('commerce: test credentials, sync products, localize, disconnect and reject viewer access', async ({ page }) => {
  test.setTimeout(90000); page.setDefaultTimeout(15000);
  const login = (email: string) => page.request.post('/api/backend/auth/login', { data: { email, password: 'commerce-browser-passphrase' } });
  expect((await login('commerce@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/knowledge?view=commerce');
  await expect(page.getByText('No store connected yet.', { exact: true })).toBeVisible();
  await page.getByLabel('HTTPS store origin', { exact: true }).fill('https://demo.myshopify.com');
  await page.getByLabel('Admin API access token', { exact: true }).fill('wrong-store-token');
  await page.getByLabel('I configured these credentials with read-only permissions.', { exact: true }).check();
  await page.getByRole('button', { name: 'Save store', exact: true }).click();
  await expect(page.getByText('Connection test required', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Test store connection', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Store connections', exact: true }).getByRole('alert')).toContainText('The connection test or sync failed.');
  expect(await page.getByRole('button', { name: 'Sync products now', exact: true }).isDisabled()).toBe(true);
  page.once('dialog', d => d.accept()); await page.getByRole('button', { name: 'Disconnect store', exact: true }).click();
  await expect(page.getByText('No store connected yet.', { exact: true })).toBeVisible();
  expect(await page.getByLabel('Admin API access token', { exact: true }).inputValue()).toBe('');
  await page.getByLabel('HTTPS store origin', { exact: true }).fill('https://demo.myshopify.com');
  await page.getByLabel('Admin API access token', { exact: true }).fill('commerce-browser-token');
  await page.getByLabel('I configured these credentials with read-only permissions.', { exact: true }).check();
  await page.getByRole('button', { name: 'Save store', exact: true }).click();
  await page.getByRole('button', { name: 'Test store connection', exact: true }).click();
  await expect(page.getByText('Connected', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Sync products now', exact: true }).click();
  await expect(page.getByText('Synced products: 1', { exact: true })).toBeVisible();
  const rows = await (await page.request.get('/api/backend/commerce')).json();
  expect(JSON.stringify(rows)).not.toContain('commerce-browser-token');
  const sources = await (await page.request.get('/api/backend/sources')).json();
  expect(rows[0].source_id).toBeTruthy();
  expect(sources.some((s: { id: string }) => s.id === rows[0].source_id)).toBe(false);
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'स्टोर कनेक्शन', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 1100 }); await page.mouse.move(0, 0);
  await page.screenshot({ path: '../docs/screenshots/t10-6-commerce.png', fullPage: true });
  page.once('dialog', d => d.accept()); await page.getByRole('button', { name: 'Disconnect store', exact: true }).click();
  await expect(page.getByText('No store connected yet.', { exact: true })).toBeVisible();
  const after = await (await page.request.get('/api/backend/sources')).json();
  expect(after.some((s: { id: string }) => s.id === rows[0].source_id)).toBe(false);
  await page.context().clearCookies(); expect((await login('commerce-viewer@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/knowledge?view=commerce');
  await expect(page.getByRole('button', { name: 'Store connections', exact: true })).toHaveCount(0);
  expect((await page.request.get('/api/backend/commerce')).status()).toBe(403);
});
