import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('Meta bot: explicit opt-in, grounded replies, human ownership, hand-back and disable', async ({ page }) => {
  test.setTimeout(90000); page.setDefaultTimeout(15000);
  const login = (email: string) => page.request.post('/api/backend/auth/login', { data: { email, password: 'meta-browser-passphrase' } });
  expect((await login('meta-bot@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/channels');
  const form = page.getByRole('form', { name: 'Connect a Meta account', exact: true });
  await form.getByLabel('Meta account or Page ID', { exact: true }).fill('543210');
  await form.getByLabel('Access token', { exact: true }).fill('synthetic-token');
  await form.getByRole('button', { name: 'Verify and connect', exact: true }).click();
  await expect(page.getByText('Bot replies off for this account', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Enable bot replies', exact: true }).click();
  await expect(page.getByText('Bot replies enabled for this account', { exact: true })).toBeVisible();
  const channels = await page.request.get('/api/backend/channels');
  const channel = (await channels.json()).find((row: { kind: string }) => row.kind === 'instagram');
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await expect(page.getByText('इस खाते के लिए बॉट जवाब चालू हैं', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  const incoming = (text: string) => page.request.post('/api/backend/_test/meta-dm/inbound', { data: { kind: 'instagram', external_id: '543210', text } });
  expect((await incoming('What is the refund policy?')).ok()).toBeTruthy();
  await page.goto('/dashboard/inbox');
  await page.getByRole('combobox', { name: 'Channel', exact: true }).selectOption('instagram');
  await page.getByRole('button', { name: /meta-test-customer/ }).click();
  const messages = page.getByRole('list', { name: 'Messages', exact: true });
  await expect(messages.getByText(/Refunds accepted within 30 days/)).toHaveCount(1);
  await expect(messages.getByText('Sent', { exact: true })).toHaveCount(1);
  await page.getByRole('button', { name: 'Take over', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Hand back to bot', exact: true })).toBeVisible();
  expect((await incoming('Could you explain refunds?')).ok()).toBeTruthy();
  await expect(messages.getByText('Could you explain refunds?', { exact: true })).toBeVisible();
  await expect(messages.getByText(/Refunds accepted within 30 days/)).toHaveCount(1);
  await page.setViewportSize({ width: 1280, height: 600 });
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await messages.focus(); await expect(messages).toBeFocused();
  await page.keyboard.press('End');
  await expect.poll(() => messages.evaluate(node => node.scrollTop)).toBeGreaterThan(0);
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 1000 }); await page.mouse.move(0, 0);
  await page.screenshot({ path: '../docs/screenshots/t10-8-meta-bot.png', fullPage: true });
  await page.getByRole('button', { name: 'Hand back to bot', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Hand back to bot', exact: true })).toHaveCount(0);
  expect((await incoming('Please confirm the refund policy.')).ok()).toBeTruthy();
  await expect(messages.getByText(/Refunds accepted within 30 days/)).toHaveCount(2);
  expect((await incoming('agent')).ok()).toBeTruthy();
  await expect(messages.getByText('Thanks, our team will reply here as soon as someone is available.', { exact: true })).toBeVisible();
  await page.goto('/dashboard/channels');
  await page.getByRole('button', { name: 'Disable bot replies', exact: true }).click();
  await expect(page.getByText('Bot replies off for this account', { exact: true })).toBeVisible();
  await page.goto('/dashboard/inbox');
  await page.getByRole('combobox', { name: 'Channel', exact: true }).selectOption('instagram');
  await page.getByRole('button', { name: /meta-test-customer/ }).click();
  await expect(page.getByRole('button', { name: 'Hand back to bot', exact: true })).toHaveCount(0);
  await page.context().clearCookies(); expect((await login('meta-bot-viewer@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/channels');
  await expect(page.getByText('Only workspace owners and admins can manage messaging accounts.', { exact: true })).toBeVisible();
  const csrf = (await page.context().cookies()).find(cookie => cookie.name === 'chatbot_csrf')!.value;
  expect((await page.request.put('/api/backend/meta-dm/channels/' + channel.id + '/bot', { headers: { 'X-CSRF-Token': csrf }, data: { enabled: true } })).status()).toBe(403);
});
