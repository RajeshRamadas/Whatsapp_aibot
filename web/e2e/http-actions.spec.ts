import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('custom actions: test gates, selected fields, explicit customer approval and role isolation', async ({ page }) => {
  test.setTimeout(90000); page.setDefaultTimeout(15000);
  const login = (email: string) => page.request.post('/api/backend/auth/login', { data: { email, password: 'actions-browser-passphrase' } });
  expect((await login('actions@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/actions'); await expect(page.getByText('No custom actions yet.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add action', exact: true }).click();
  const form = page.getByRole('form', { name: 'Add action', exact: true });
  await form.getByLabel('Action name', { exact: true }).fill('stock');
  await form.getByLabel('When should the bot use this action?', { exact: true }).fill('Look up product stock.');
  await form.getByLabel('HTTPS URL template', { exact: true }).fill('https://api.example.com/stock/{sku}');
  await form.getByRole('button', { name: 'Add input', exact: true }).click();
  await form.getByLabel('Input name', { exact: true }).fill('sku');
  await form.getByLabel('Input description', { exact: true }).fill('Product code');
  await form.getByLabel('Validation pattern (optional)', { exact: true }).fill('[A-Z0-9-]{1,20}');
  await form.getByLabel('Field name', { exact: true }).fill('stock'); await form.getByLabel('Response JSON path', { exact: true }).fill('$.stock');
  await form.getByLabel('This action returns or changes personal data', { exact: true }).uncheck();
  await form.getByRole('combobox', { name: 'Authentication', exact: true }).selectOption('bearer');
  await form.getByLabel('API key or token', { exact: true }).fill('browser-action-secret');
  await form.getByRole('button', { name: 'Save paused action', exact: true }).click();
  let card = page.getByRole('region', { name: 'stock', exact: true });
  await expect(card.getByRole('button', { name: 'Enable action', exact: true })).toBeDisabled();
  await card.getByText('Test action and call history', { exact: true }).click();
  await card.getByRole('textbox', { name: 'Sample inputs (JSON object)', exact: true }).fill('{"sku":"FAIL"}');
  await card.getByRole('button', { name: 'Run test action', exact: true }).click();
  await expect(card.getByText('Test failed. Check the result before trying again.', { exact: true })).toBeVisible();
  await expect(card.getByRole('button', { name: 'Enable action', exact: true })).toBeDisabled();
  await card.getByRole('textbox', { name: 'Sample inputs (JSON object)', exact: true }).fill('{"sku":"SKU"}');
  await card.getByRole('button', { name: 'Run test action', exact: true }).click();
  await expect(card.getByText('Test passed. This version can be enabled.', { exact: true })).toBeVisible();
  const result = card.getByRole('region', { name: 'Test result', exact: true });
  await expect(result.locator('pre').first()).toHaveText('{\n  "stock": 5\n}');
  await result.getByText('Raw response (credentials masked)', { exact: true }).click();
  await expect(result.locator('pre').last()).toContainText('Admin-only synthetic field');
  await card.getByRole('button', { name: 'Clear test response', exact: true }).click();
  await card.getByRole('button', { name: 'Enable action', exact: true }).click();
  await expect(card.getByText('Enabled for customer chat', { exact: true })).toBeVisible();
  expect(await page.content()).not.toContain('browser-action-secret');
  const base = '/api/backend/chat/pub_actions_demo/widget';
  let conversation: string | undefined;
  async function turn(message: string, id = crypto.randomUUID()) {
    const response = await page.request.post(base + '/turns', { headers: { Origin: 'http://localhost:3000' }, data: { message, request_id: id, ...(conversation ? { conversation_id: conversation } : {}) } });
    expect(response.status()).toBe(202); conversation = (await response.json()).conversation_id;
    const completed = await (await page.request.get(base + '/turns/' + id)).json();
    expect(completed.state).toBe('complete'); return completed;
  }
  expect((await turn('LOOKUP SKU')).answer).toBe('Available: 5 [1]');
  const metrics = async () => (await (await page.request.get('/api/backend/_test/http-actions')).json());
  expect(JSON.stringify((await metrics()).results)).not.toContain('Admin-only');
  await card.getByRole('button', { name: 'Edit action', exact: true }).click();
  const edit = page.getByRole('form', { name: 'Edit action', exact: true });
  await expect(edit.getByLabel('API key or token', { exact: true })).toHaveValue('');
  await edit.getByLabel('Action name', { exact: true }).fill('change_stock');
  await edit.getByRole('combobox', { name: 'HTTP method', exact: true }).selectOption('POST');
  await edit.getByLabel('I allow this action to change data in the connected system.', { exact: true }).check();
  await expect(edit.getByLabel('Require customer confirmation before each change', { exact: true })).toBeChecked();
  await edit.getByLabel('API key or token', { exact: true }).fill('browser-new-action-secret');
  await edit.getByRole('button', { name: 'Save paused action', exact: true }).click();
  card = page.getByRole('region', { name: 'change_stock', exact: true });
  await expect(card.getByRole('button', { name: 'Enable action', exact: true })).toBeDisabled();
  if (!await card.getByRole('textbox', { name: 'Sample inputs (JSON object)', exact: true }).isVisible()) await card.getByText('Test action and call history', { exact: true }).click();
  await card.getByRole('textbox', { name: 'Sample inputs (JSON object)', exact: true }).fill('{"sku":"SKU"}');
  await expect(card.getByRole('button', { name: 'Run test action', exact: true })).toBeDisabled();
  await card.getByLabel('I approve this test changing data in the connected system.', { exact: true }).check();
  await card.getByRole('button', { name: 'Run test action', exact: true }).click();
  await expect(card.getByText('Test passed. This version can be enabled.', { exact: true })).toBeVisible();
  await card.getByRole('button', { name: 'Enable action', exact: true }).click();
  await expect(card.getByText('Enabled for customer chat', { exact: true })).toBeVisible();
  await page.request.post('/api/backend/_test/http-actions/reset');
  const requestId = crypto.randomUUID(), pending = await turn('CHANGE SKU', requestId);
  const command = pending.answer.match(/ACTION [a-f0-9]{12}/)![0];
  expect((await metrics()).writes).toBe(0); await turn('CHANGE SKU', requestId); expect((await metrics()).writes).toBe(0);
  expect((await turn(command)).answer).toContain('stock: 5'); expect((await metrics()).writes).toBe(1);
  await turn(command); expect((await metrics()).writes).toBe(1);
  await card.getByRole('button', { name: 'Clear test response', exact: true }).click();
  await page.getByRole('button', { name: 'Refresh actions', exact: true }).click();
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click(); await expect(page.getByRole('heading', { name: 'कस्टम एक्शन', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 320, height: 900 }); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await card.getByText('Test action and call history', { exact: true }).click();
  await page.setViewportSize({ width: 1280, height: 1100 }); await page.mouse.move(0, 0);
  await page.screenshot({ path: '../docs/screenshots/t10-3-custom-actions.png', fullPage: true });
  await card.getByRole('button', { name: 'Pause action', exact: true }).click(); await expect(card.getByText('Paused', { exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept()); await card.getByRole('button', { name: 'Delete action', exact: true }).click();
  await expect(page.getByText('No custom actions yet.', { exact: true })).toBeVisible();
  await page.context().clearCookies(); expect((await login('actions-viewer@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/actions'); await expect(page.getByText('Only owners and admins can manage custom actions.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Add action', exact: true })).toHaveCount(0);
  expect((await page.request.get('/api/backend/http-actions')).status()).toBe(403);
});
