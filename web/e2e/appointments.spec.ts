import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('appointments: configure, hold, confirm, remind, reschedule, cancel and restrict roles', async ({ page }) => {
  test.setTimeout(60000);
  const login = (email: string) => page.request.post('/api/backend/auth/login', { data: { email, password: 'appointment-browser-passphrase' } });
  expect((await login('appointments@example.com')).ok()).toBeTruthy();
  let release: () => void = () => {};
  const loading = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/backend/appointments/catalog', async route => { await loading; await route.continue(); });
  await page.goto('/dashboard/appointments');
  await expect(page.getByText('Loading appointments…', { exact: true })).toBeVisible();
  release();
  await page.unrouteAll({ behavior: 'wait' });
  await expect(page.getByText('No slots in this date range. An admin can add availability.')).toBeVisible();
  await page.getByText('Services and staff', { exact: true }).click();
  const service = page.getByRole('form', { name: 'Service', exact: true });
  await service.getByRole('textbox', { name: 'Name', exact: true }).fill('Consultation');
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await expect(page.getByRole('form', { name: 'सेवा', exact: true }).getByRole('textbox', { name: 'नाम', exact: true })).toHaveValue('Consultation');
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await page.route('**/api/backend/appointments/services', route => route.fulfill({ status: 503, json: {} }));
  await service.getByRole('button', { name: 'Save service', exact: true }).click();
  await expect(page.getByText('Could not save this change. Check the details and refresh availability.')).toBeVisible();
  await expect(service.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue('Consultation');
  await page.unroute('**/api/backend/appointments/services');
  await service.getByRole('button', { name: 'Save service', exact: true }).click();
  await expect(service.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue('');
  const staff = page.getByRole('form', { name: 'Staff member', exact: true });
  await staff.getByRole('textbox', { name: 'Name', exact: true }).fill('Demo specialist');
  await staff.getByRole('button', { name: 'Save staff member', exact: true }).click();
  const availability = page.getByRole('form', { name: 'Add availability', exact: true });
  await availability.getByRole('combobox', { name: 'Service', exact: true }).selectOption({ label: 'Consultation' });
  await availability.getByRole('combobox', { name: 'Staff member', exact: true }).selectOption({ label: 'Demo specialist' });
  const starts = new Date(Date.now() + 20 * 60000); starts.setSeconds(0, 0);
  await availability.getByLabel('Slot start', { exact: true }).fill(starts.toISOString().slice(0, 16));
  await availability.getByRole('button', { name: 'Add availability', exact: true }).click();
  await page.getByRole('button', { name: 'Reserve this slot', exact: true }).click();
  const composer = page.getByRole('form', { name: 'Hold an appointment', exact: true });
  await composer.getByRole('combobox', { name: 'Customer conversation', exact: true }).selectOption({ index: 1 });
  await composer.getByRole('textbox', { name: 'Customer name', exact: true }).fill('Demo customer');
  await composer.getByRole('textbox', { name: 'International phone number', exact: true }).fill('+919999000001');
  await composer.getByRole('combobox', { name: 'Customer language', exact: true }).selectOption('hi');
  await composer.getByRole('checkbox').check();
  await composer.getByRole('button', { name: 'Hold for five minutes', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Confirm booking', exact: true }).click();
  await expect(page.getByText('Reminder: Sent', { exact: true })).toBeVisible();
  const rows = await (await page.request.get('/api/backend/appointments/bookings')).json();
  expect(rows[0].language).toBe('hi'); expect(new Date(rows[0].starts_at).toISOString()).toBe(starts.toISOString());
  const messages = await (await page.request.get('/api/backend/conversations/' + rows[0].conversation_id + '/messages')).json();
  expect(messages.some((m: { content: string }) => m.content.includes('रिमाइंडर'))).toBeTruthy();
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await page.setViewportSize({ width: 320, height: 1000 });
  await page.evaluate(() => document.fonts.ready);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 1280, height: 1000 });
  await page.screenshot({ path: 'test-results/appointments.png', fullPage: true });
  await page.getByRole('button', { name: 'English', exact: true }).click();
  const later = new Date(starts.getTime() + 90 * 60000);
  await availability.getByLabel('Slot start', { exact: true }).fill(later.toISOString().slice(0, 16));
  await availability.getByRole('button', { name: 'Add availability', exact: true }).click();
  await page.getByRole('button', { name: 'Reschedule', exact: true }).click();
  await page.getByRole('button', { name: 'Reserve this slot', exact: true }).click();
  await composer.getByRole('button', { name: 'Hold for five minutes', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Confirm booking', exact: true }).click();
  const bookings = page.getByRole('region', { name: 'Bookings', exact: true });
  await expect(bookings.getByText('Cancelled', { exact: true })).toHaveCount(1);
  page.once('dialog', dialog => dialog.accept());
  await bookings.getByRole('button', { name: 'Cancel booking', exact: true }).click();
  await expect(bookings.getByText('Cancelled', { exact: true })).toHaveCount(2);
  expect((await login('appointment-agent@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/appointments');
  await expect(page.getByText('Services and staff', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('form', { name: 'Hold an appointment', exact: true })).toBeVisible();
  expect((await page.request.post('/api/backend/appointments/staff', { data: { name: 'Denied' } })).status()).toBe(403);
  expect((await login('appointment-reader@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/appointments');
  await expect(page.getByText('Only owners, admins and agents can access appointments.')).toBeVisible();
  await expect(page.getByRole('link', { name: 'Appointments', exact: true })).toHaveCount(0);
  expect((await page.request.get('/api/backend/appointments/catalog')).status()).toBe(403);
});
