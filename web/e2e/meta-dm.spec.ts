import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('Meta accounts: verify, receive signed DMs, reply within window and disconnect', async ({ page }) => {
  test.setTimeout(90000); page.setDefaultTimeout(15000);
  const login = (email: string) => page.request.post('/api/backend/auth/login', { data: { email, password: 'meta-browser-passphrase' } });
  expect((await login('meta-dm@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/channels');
  await expect(page.getByText('No Instagram or Messenger accounts connected.', { exact: true })).toBeVisible();
  const form = page.getByRole('form', { name: 'Connect a Meta account', exact: true });
  await form.getByLabel('Meta account or Page ID', { exact: true }).fill('999');
  await form.getByLabel('Access token', { exact: true }).fill('synthetic-token');
  await form.getByRole('button', { name: 'Verify and connect', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'Meta could not verify this account' })).toBeVisible();
  await expect(form.getByLabel('Access token', { exact: true })).toHaveValue('');
  await form.getByLabel('Meta account or Page ID', { exact: true }).fill('654321');
  await form.getByLabel('Access token', { exact: true }).fill('synthetic-token');
  await form.getByRole('button', { name: 'Verify and connect', exact: true }).click();
  await expect(page.getByText('Meta demo account', { exact: true })).toBeVisible();
  const channels = await page.request.get('/api/backend/channels'); expect(await channels.text()).not.toContain('synthetic-token');
  const incoming = (old: boolean) => page.request.post('/api/backend/_test/meta-dm/inbound', { data: { kind: 'instagram', external_id: '654321', old } });
  expect((await incoming(false)).ok()).toBeTruthy();
  await page.goto('/dashboard/inbox');
  await page.getByRole('combobox', { name: 'Channel', exact: true }).selectOption('instagram');
  await page.getByRole('button', { name: /meta-test-customer/ }).click();
  await page.getByRole('button', { name: 'Take over', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Hand back to bot', exact: true })).toHaveCount(0);
  const composer = page.getByRole('textbox', { name: 'Reply or internal note', exact: true });
  await composer.fill('ह'.repeat(400));
  await expect(page.getByText('This message is too long for this channel. Shorten it before sending.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Send reply', exact: true })).toBeDisabled();
  await composer.fill('Thanks, we can help.'); await page.getByRole('button', { name: 'Send reply', exact: true }).click();
  await expect(page.getByRole('list', { name: 'Messages', exact: true }).getByText('Thanks, we can help.', { exact: true })).toBeVisible();
  await expect(page.getByRole('list', { name: 'Messages', exact: true }).getByText('Sent', { exact: true })).toBeVisible();
  expect((await incoming(true)).ok()).toBeTruthy(); await page.reload();
  await page.getByRole('button', { name: /meta-expired-customer/ }).click();
  await expect(page.getByText('Replies require a connected account and a customer message within the last 24 hours.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Send reply', exact: true })).toBeDisabled();
  await page.goto('/dashboard/channels');
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Instagram और Messenger', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 320, height: 900 }); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 1000 }); await page.mouse.move(0, 0);
  await page.screenshot({ path: '../docs/screenshots/t10-8-meta-accounts.png', fullPage: true });
  page.once('dialog', dialog => dialog.accept()); await page.getByRole('button', { name: 'Disconnect account', exact: true }).click();
  await expect(page.getByText('No Instagram or Messenger accounts connected.', { exact: true })).toBeVisible();
  await page.context().clearCookies(); expect((await login('meta-viewer@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/channels'); await expect(page.getByText('Only workspace owners and admins can manage messaging accounts.', { exact: true })).toBeVisible();
  expect((await page.request.post('/api/backend/meta-dm/channels', { data: { kind: 'instagram', external_id: '654321', access_token: 'synthetic-token' } })).status()).toBe(403);
});
