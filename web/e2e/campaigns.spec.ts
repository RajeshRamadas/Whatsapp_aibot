test('campaign loading, empty and error states recover; viewers cannot use the page', async ({ page }) => {
  await page.request.post('/api/backend/auth/login', { data: { email: 'campaigns@example.com', password: 'campaigns-browser-passphrase' } });
  let release: () => void = () => {}; const pending = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/backend/campaigns?*', async route => { await pending; await route.fulfill({ status: 503, json: {} }); });
  await page.goto('/dashboard/campaigns');
  await expect(page.getByRole('status').filter({ hasText: 'Loading…' })).toBeVisible(); release();
  await expect(page.getByRole('alert').filter({ hasText: 'Could not load records' })).toBeVisible();
  await page.route('**/api/backend/campaigns?*', route => route.fulfill({ json: [] }));
  await page.getByRole('button', { name: 'Retry', exact: true }).click();
  await expect(page.getByText('No records yet.', { exact: true })).toBeVisible();
  await page.request.post('/api/backend/auth/login', { data: { email: 'campaign-reader@example.com', password: 'campaigns-browser-passphrase' } });
  await page.goto('/dashboard/campaigns');
  await expect(page.getByText('Only workspace owners and admins can manage campaigns.', { exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Campaigns', exact: true })).toHaveCount(0);
});
