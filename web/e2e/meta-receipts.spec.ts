import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('Messenger receipts update the inbox without regressing Read to Delivered', async ({ page }) => {
  test.setTimeout(90000); page.setDefaultTimeout(15000);
  expect((await page.request.post('/api/backend/auth/login', { data: { email: 'meta-receipts@example.com', password: 'meta-browser-passphrase' } })).ok()).toBeTruthy();
  await page.goto('/dashboard/channels');
  const form = page.getByRole('form', { name: 'Connect a Meta account', exact: true });
  await form.getByRole('combobox', { name: 'Channel', exact: true }).selectOption('messenger');
  await form.getByLabel('Meta account or Page ID', { exact: true }).fill('765432');
  await form.getByLabel('Access token', { exact: true }).fill('synthetic-token');
  await form.getByRole('button', { name: 'Verify and connect', exact: true }).click();
  await expect(page.getByText('Meta demo account', { exact: true })).toBeVisible();
  expect((await page.request.post('/api/backend/_test/meta-dm/inbound', { data: { kind: 'messenger', external_id: '765432' } })).ok()).toBeTruthy();
  await page.goto('/dashboard/inbox');
  await page.getByRole('combobox', { name: 'Channel', exact: true }).selectOption('messenger');
  await page.getByRole('button', { name: /meta-test-customer/ }).click();
  await page.getByRole('button', { name: 'Take over', exact: true }).click();
  await page.getByRole('textbox', { name: 'Reply or internal note', exact: true }).fill('We can help with your order.');
  await page.getByRole('button', { name: 'Send reply', exact: true }).click();
  const messages = page.getByRole('list', { name: 'Messages', exact: true });
  await expect(messages.getByText('Sent', { exact: true })).toBeVisible();
  const receipt = (status: string) => page.request.post('/api/backend/_test/meta-dm/receipt', { data: { kind: 'messenger', external_id: '765432', status } });
  expect((await receipt('delivered')).ok()).toBeTruthy();
  await expect(messages.getByText('Delivered', { exact: true })).toBeVisible();
  expect((await receipt('read')).ok()).toBeTruthy();
  await expect(messages.getByText('Read', { exact: true })).toBeVisible();
  expect((await receipt('delivered')).ok()).toBeTruthy();
  await expect(messages.getByText('Read', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await expect(page.getByRole('list', { name: 'संदेश', exact: true }).getByText('पढ़ लिया गया', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 1000 }); await page.mouse.move(0, 0);
  await page.screenshot({ path: '../docs/screenshots/t10-8-meta-receipts.png', fullPage: true });
});
