import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('spreadsheets: reimport, exact counts, safe SQL, citations, pause and role isolation', async ({ page }) => {
  test.setTimeout(90000); page.setDefaultTimeout(15000);
  const login = (email: string) => page.request.post('/api/backend/auth/login', { data: { email, password: 'spreadsheets-browser-passphrase' } });
  expect((await login('spreadsheets@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/knowledge?view=tables');
  await expect(page.getByText('This older spreadsheet needs reprocessing before exact queries are available.', { exact: true })).toBeVisible();
  page.once('dialog', d => d.accept()); await page.getByRole('button', { name: 'Reprocess spreadsheet', exact: true }).click();
  const card = page.getByRole('region', { name: 'CSV', exact: true });
  await expect(card.getByText('Imported rows: 4 · Exact answers paused', { exact: true })).toBeVisible();
  await card.getByRole('button', { name: 'Preview rows', exact: true }).click();
  await expect(card.getByRole('cell', { name: '3500000', exact: true })).toBeVisible();
  await card.getByText('Test an exact query', { exact: true }).click();
  const catalog = await (await page.request.get('/api/backend/tables')).json(), table = catalog.tables[0];
  const sql = card.getByRole('textbox', { name: 'Read-only SELECT', exact: true });
  await sql.fill('DELETE FROM ' + table.table_name);
  await card.getByRole('button', { name: 'Run exact query', exact: true }).click();
  await expect(card.getByRole('alert')).toContainText('Query could not be completed.');
  await sql.fill(`SELECT COUNT(*) AS total, SUM(c2) AS cost FROM ${table.table_name} WHERE c1='2BHK' AND c2 < 4000000`);
  await card.getByRole('button', { name: 'Run exact query', exact: true }).click();
  await expect(card.getByRole('cell', { name: '2', exact: true })).toBeVisible();
  await expect(card.getByRole('cell', { name: '7400000', exact: true })).toBeVisible();
  await card.getByRole('button', { name: 'Enable exact answers', exact: true }).click();
  await expect(card.getByText('Imported rows: 4 · Exact answers enabled', { exact: true })).toBeVisible();
  const base = '/api/backend/chat/pub_spreadsheets_demo/widget';
  async function ask() {
    const id = crypto.randomUUID();
    expect((await page.request.post(base + '/turns', { headers: { Origin: 'http://localhost:3000' }, data: { request_id: id, message: 'EXACT PLOTS: how many 2BHK plots under ₹40 lakh?' } })).status()).toBe(202);
    const result = await (await page.request.get(base + '/turns/' + id)).json(); expect(result.state).toBe('complete'); return result;
  }
  const answer = await ask(); expect(answer.answer).toBe('There are 2 matching plots. [1]');
  expect(answer.sources).toEqual([{ number: 1, filename: 'plots.csv', heading: 'CSV', page: null }]);
  await card.getByRole('button', { name: 'Pause exact answers', exact: true }).click();
  await expect(card.getByText('Imported rows: 4 · Exact answers paused', { exact: true })).toBeVisible();
  const paused = await ask(); expect(paused.answer).toBe('That information is currently unavailable.'); expect(paused.sources).toEqual([]);
  await card.getByRole('button', { name: 'Enable exact answers', exact: true }).click();
  await expect(card.getByRole('button', { name: 'Pause exact answers', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click(); await expect(page.getByRole('heading', { name: 'स्प्रेडशीट से सटीक उत्तर', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 320, height: 900 }); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 1100 }); await page.mouse.move(0, 0);
  await page.screenshot({ path: '../docs/screenshots/t10-4-spreadsheet-answers.png', fullPage: true });
  const csrf = (await page.context().cookies()).find(c => c.name === 'chatbot_csrf')!.value;
  expect((await page.request.delete('/api/backend/sources/' + table.source_id, { headers: { 'X-CSRF-Token': csrf } })).status()).toBe(204);
  await page.getByRole('button', { name: 'Refresh spreadsheets', exact: true }).click();
  await expect(page.getByText('No spreadsheets yet. Upload a CSV or XLSX in Documents.', { exact: true })).toBeVisible();
  expect((await page.request.get('/api/backend/tables/' + table.id + '/preview')).status()).toBe(404);
  await page.context().clearCookies(); expect((await login('sheets-viewer@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/knowledge?view=tables');
  await expect(page.getByRole('button', { name: 'Exact spreadsheet answers', exact: true })).toHaveCount(0);
  expect((await page.request.get('/api/backend/tables')).status()).toBe(403);
});
