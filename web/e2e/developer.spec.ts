import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const password = 'developer-browser-passphrase';
test('developer API: scoped key, replay, private boundary, revoke and bilingual reference', async ({ page }) => {
  page.setDefaultTimeout(15000);
  expect((await page.request.post('/api/backend/auth/login', { data: { email: 'developer@example.com', password } })).ok()).toBeTruthy();
  await page.goto('/dashboard/developer');
  await expect(page.getByText('No API keys yet. Create one to connect an integration.', { exact: true })).toBeVisible();
  await page.getByLabel('Key name', { exact: true }).fill('Contact sync');
  await page.getByLabel('Read knowledge', { exact: true }).uncheck();
  await page.getByLabel('Read contacts', { exact: true }).check();
  await page.getByLabel('Manage contacts', { exact: true }).check();
  await page.getByRole('button', { name: 'Create API key', exact: true }).click();
  const raw = await page.getByRole('textbox', { name: 'New API key', exact: true }).inputValue();
  expect(raw.startsWith('sk_live_')).toBe(true);
  const headers = { Authorization: 'Bearer ' + raw, 'Idempotency-Key': 'browser-contact' };
  const data = { channel: 'web', external_user: 'synthetic-customer', name: 'Demo contact' };
  const first = await page.request.post('/api/backend/public/contacts', { headers, data });
  expect(first.status()).toBe(201); expect(first.headers()['idempotency-replayed']).toBe('false');
  expect(first.headers()['api-version']).toBe('1'); expect(first.headers()['cache-control']).toContain('no-store');
  expect(first.headers().location).toContain('/api/backend/public/contacts/');
  const again = await page.request.post('/api/backend/public/contacts', { headers, data });
  expect(again.headers()['idempotency-replayed']).toBe('true'); expect(await again.json()).toEqual(await first.json());
  expect((await page.request.post('/api/backend/public/contacts', { headers, data: { ...data, name: 'Changed' } })).status()).toBe(409);
  expect((await page.request.get('/api/backend/public/messages', { headers })).status()).toBe(403);
  expect((await page.request.get('/api/backend/tenant', { headers })).status()).toBe(403);
  expect((await page.request.get('/api/backend/public/contacts')).status()).toBe(401);
  expect((await page.request.get(first.headers().location, { headers })).status()).toBe(200);
  const schema = await (await page.request.get('/api/backend/public/openapi.json')).json();
  expect(schema.paths['/contacts'].post.parameters.some((v: { name: string; required: boolean }) => v.name === 'Idempotency-Key' && v.required)).toBe(true);
  expect(schema.paths['/contacts'].get.responses['422'].content['application/json'].schema.$ref).toContain('ErrorResponse');
  const docs = await page.request.get('/api/backend/public/docs'); expect(await docs.text()).toContain('./openapi.json');
  await page.getByRole('button', { name: 'I saved the key', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'New API key', exact: true })).toHaveCount(0);
  await page.reload(); await expect(page.getByRole('textbox', { name: 'New API key', exact: true })).toHaveCount(0);
  expect(await page.content()).not.toContain(raw);
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'डेवलपर API', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 1100 }); await page.mouse.move(0, 0);
  await page.screenshot({ path: '../docs/screenshots/t10-1-developer-api.png', fullPage: true });
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Revoke key: Contact sync', exact: true }).click();
  await expect(page.getByText('Revoked', { exact: true })).toBeVisible();
  expect((await page.request.get('/api/backend/public/contacts', { headers })).status()).toBe(401);
  await page.context().clearCookies();
  expect((await page.request.post('/api/backend/auth/login', { data: { email: 'developer-viewer@example.com', password } })).ok()).toBeTruthy();
  await page.goto('/dashboard/developer');
  await expect(page.getByText('Only workspace owners and admins can manage API keys.', { exact: true })).toBeVisible();
  await expect(page.getByRole('form', { name: 'Create API key', exact: true })).toHaveCount(0);
});
