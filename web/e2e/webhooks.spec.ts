import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const password = 'webhooks-browser-passphrase';
test('outgoing events: consent, failure log, safe resend, pause, remove and role isolation', async ({ page }) => {
  test.setTimeout(90000); page.setDefaultTimeout(15000);
  expect((await page.request.post('/api/backend/auth/login', { data: { email: 'webhooks@example.com', password } })).ok()).toBeTruthy();
  await page.goto('/dashboard/developer');
  await expect(page.getByText('No event destinations yet.', { exact: true })).toBeVisible();
  await page.getByText('Add event destination', { exact: true }).click();
  await page.getByLabel('Destination name', { exact: true }).fill('Order automation');
  await page.getByLabel('Destination HTTPS URL', { exact: true }).fill('https://receiver.example.com/events');
  await page.getByRole('button', { name: 'Save paused destination', exact: true }).click();
  const secret = await page.getByRole('textbox', { name: 'Signing secret', exact: true }).inputValue();
  expect(secret.startsWith('whsec_')).toBe(true);
  await page.getByRole('button', { name: 'I saved the signing secret', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Signing secret', exact: true })).toHaveCount(0);
  const card = page.getByRole('region', { name: 'Order automation', exact: true });
  await expect(card.getByRole('button', { name: 'Enable delivery', exact: true })).toBeDisabled();
  await card.getByLabel('I approve sending these record IDs and status metadata to this destination.', { exact: true }).check();
  await card.getByRole('button', { name: 'Enable delivery', exact: true }).click();
  await expect(card.getByText('Delivery enabled', { exact: true })).toBeVisible();
  const csrf = (await page.context().cookies()).find(c => c.name === 'chatbot_csrf')!.value;
  const credential = await (await page.request.post('/api/backend/api-keys', { headers: { 'X-CSRF-Token': csrf }, data: { name: 'Synthetic capture', scopes: ['leads:write'] } })).json();
  const conversations = await (await page.request.get('/api/backend/conversations')).json();
  await page.request.post('/api/backend/_test/webhooks/fail-next');
  const lead = await page.request.post('/api/backend/public/leads', { headers: { Authorization: 'Bearer ' + credential.key, 'Idempotency-Key': 'event-demo-lead' }, data: { conversation_id: conversations[0].id, fields: { need: 'Synthetic demo request' } } });
  expect(lead.status()).toBe(201);
  await card.getByText('Delivery history', { exact: true }).click();
  await card.getByRole('button', { name: 'Refresh delivery history', exact: true }).click();
  await expect(card.getByText('lead.created · Failed', { exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await card.getByRole('button', { name: 'Resend event', exact: true }).click();
  await expect(card.getByText('lead.created · Delivered', { exact: true })).toBeVisible();
  await expect(card.getByText(/Last successful delivery:/)).not.toContainText('Never');
  expect((await (await page.request.get('/api/backend/_test/webhooks/received')).json()).events).toBe(1);
  expect(await page.content()).not.toContain(secret);
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'बाहरी इवेंट', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByText('Add event destination', { exact: true }).click();
  await card.getByText('Delivery history', { exact: true }).click();
  await page.setViewportSize({ width: 1280, height: 1100 }); await page.mouse.move(0, 0);
  await page.getByRole('heading', { name: 'Outgoing events', exact: true }).scrollIntoViewIfNeeded();
  await page.getByRole('region', { name: 'Outgoing events', exact: true }).screenshot({ path: '../docs/screenshots/t10-2-outgoing-events.png' });
  await card.getByRole('button', { name: 'Pause delivery', exact: true }).click();
  await expect(card.getByText('Delivery paused', { exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept()); await card.getByRole('button', { name: 'Delete destination', exact: true }).click();
  await expect(page.getByText('No event destinations yet.', { exact: true })).toBeVisible();
  await page.context().clearCookies(); expect((await page.request.post('/api/backend/auth/login', { data: { email: 'webhooks-viewer@example.com', password } })).ok()).toBeTruthy();
  await page.goto('/dashboard/developer'); await expect(page.getByRole('heading', { name: 'Outgoing events', exact: true })).toHaveCount(0);
  expect((await page.request.get('/api/backend/webhook-endpoints')).status()).toBe(403);
});
