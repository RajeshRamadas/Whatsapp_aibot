import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('Meta authorization: denial, cancellation, account selection and session permissions', async ({ page }) => {
  test.setTimeout(90000); page.setDefaultTimeout(15000);
  const login = (email: string) => page.request.post('/api/backend/auth/login', { data: { email, password: 'meta-browser-passphrase' } });
  expect((await login('meta-oauth@example.com')).ok()).toBeTruthy();
  let deny = true;
  await page.route('https://www.facebook.com/**/dialog/oauth*', async route => {
    const source = new URL(route.request().url()), callback = new URL(source.searchParams.get('redirect_uri')!);
    callback.searchParams.set('state', source.searchParams.get('state')!);
    callback.searchParams.set(deny ? 'error' : 'code', deny ? 'access_denied' : 'synthetic-authorization-code');
    await route.fulfill({ status: 302, headers: { location: callback.toString() }, body: '' });
  });
  await page.goto('/dashboard/channels');
  await page.getByRole('button', { name: 'Authorize with Meta', exact: true }).click();
  await expect(page.getByText('Meta authorization was declined. You can start again when ready.', { exact: true })).toBeVisible();
  deny = false;
  await page.getByRole('button', { name: 'Authorize with Meta', exact: true }).click();
  await expect(page.getByRole('option', { name: 'Demo Instagram (888111)', exact: true })).toHaveCount(1);
  const identity = new URL(page.url()).searchParams.get('meta_oauth')!;
  const status = await page.request.get('/api/backend/meta-dm/oauth/' + identity);
  expect(status.ok()).toBeTruthy(); expect(await status.text()).not.toContain('synthetic-page-token');
  expect(await status.text()).not.toContain('synthetic-authorization-code');
  await page.getByRole('button', { name: 'Cancel authorization', exact: true }).click();
  await expect(page.getByText('Authorization cancelled.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Authorize with Meta', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Authorized account', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Meta खाते को अनुमति दें', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 1000 }); await page.mouse.move(0, 0);
  await page.screenshot({ path: '../docs/screenshots/t10-8-meta-oauth.png', fullPage: true });
  await page.getByRole('combobox', { name: 'Authorized account', exact: true }).selectOption('888111');
  await page.getByRole('button', { name: 'Connect selected account', exact: true }).click();
  await expect(page.getByText('Account connected. You can now reply from Inbox.', { exact: true })).toBeVisible();
  await expect(page.getByText('Demo Instagram', { exact: true })).toBeVisible();
  expect(new URL(page.url()).searchParams.has('meta_oauth')).toBe(false);
  const connected = await page.request.get('/api/backend/channels'); expect(await connected.text()).not.toContain('synthetic-page-token');
  await page.context().clearCookies(); expect((await login('meta-oauth-viewer@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/channels');
  await expect(page.getByText('Only workspace owners and admins can manage messaging accounts.', { exact: true })).toBeVisible();
  expect((await page.request.get('/api/backend/meta-dm/oauth/' + identity)).status()).toBe(403);
});
