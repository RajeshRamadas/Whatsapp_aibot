import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('accuracy: save tests, approve paid calls, compare history, inspect failures and restrict readers', async ({ page }) => {
  test.setTimeout(90000); page.setDefaultTimeout(15000);
  const login = (email: string) => page.request.post('/api/backend/auth/login', { data: { email, password: 'accuracy-browser-passphrase' } });
  expect((await login('accuracy@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/analytics');
  await page.getByRole('link', { name: 'Accuracy runs', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Analytics', exact: true }).first()).toHaveAttribute('aria-current', 'page');
  await expect(page.getByText('No accuracy runs yet. Select questions and start a run to save a baseline.')).toBeVisible();
  await page.getByText('Add or edit test questions', { exact: true }).click();
  const editor = page.getByRole('form', { name: 'Add test question', exact: true });
  await editor.getByRole('textbox', { name: 'Customer question', exact: true }).fill('What is the refund period?');
  await editor.getByRole('textbox', { name: 'Required answer phrases', exact: true }).fill('30 days');
  await editor.getByRole('textbox', { name: 'Expected source filename (optional)', exact: true }).fill('accuracy-refunds.txt');
  await editor.getByRole('button', { name: 'Save test question', exact: true }).click();
  await expect(editor.getByRole('textbox', { name: 'Customer question', exact: true })).toHaveValue('');
  await editor.getByRole('textbox', { name: 'Customer question', exact: true }).fill('Do you repair cars?');
  await editor.getByLabel('The bot should decline or ask for human help', { exact: true }).check();
  await editor.getByRole('button', { name: 'Save test question', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Do you repair cars?', exact: true })).toBeVisible();
  await page.getByText('Add or edit test questions', { exact: true }).click();
  await page.getByRole('button', { name: 'Select first 100 questions', exact: true }).click();
  const start = page.getByRole('form', { name: 'Run selected questions', exact: true });
  for (const label of ['Baseline', 'Follow-up']) {
    if (label === 'Follow-up') expect((await page.request.post('/api/backend/_test/accuracy/improve')).ok()).toBeTruthy();
    await start.getByRole('textbox', { name: 'Run name', exact: true }).fill(label);
    await expect(start.getByRole('button', { name: 'Run selected questions', exact: true })).toBeDisabled();
    await start.getByLabel('I approve the model calls for these selected questions.', { exact: true }).check();
    await start.getByRole('button', { name: 'Run selected questions', exact: true }).click();
    const detail = page.getByRole('region', { name: 'Saved run results', exact: true });
    await expect(detail.getByRole('heading', { name: label, exact: true })).toBeVisible();
    await expect(detail.getByText(label === 'Baseline' ? 'Pass rate: 50% · Expected-source hit rate: 100%' : 'Pass rate: 100% · Expected-source hit rate: 100%', { exact: true })).toBeVisible();
    await expect(detail.getByText('2 of 2 questions finished', { exact: false })).toBeVisible();
    if (label === 'Baseline') await expect(detail.getByText('Not passed', { exact: true }).first()).toBeVisible();
  }
  await expect(page.getByText('Pass rate, oldest to newest:', { exact: false })).toBeVisible();
  const history = await (await page.request.get('/api/backend/evals/runs')).json();
  expect(history).toHaveLength(2); expect(history.map((r: { accuracy: number }) => r.accuracy)).toEqual([1, 0.5]);
  // Opening the selected row again must reload details rather than leave a permanent spinner.
  await page.getByRole('button', { name: 'View Follow-up', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Saved run results', exact: true }).getByRole('heading', { name: 'Follow-up', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'सटीकता जाँच', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 1100 }); await page.mouse.move(0, 0);
  await page.screenshot({ path: '../docs/screenshots/t9-12-accuracy.png', fullPage: true });
  const caseCard = page.getByRole('region', { name: 'Test questions', exact: true }).getByRole('listitem').filter({ hasText: 'What is the refund period?' });
  await caseCard.getByRole('button', { name: 'Edit test question', exact: true }).click();
  const edit = page.getByRole('form', { name: 'Edit test question', exact: true });
  await edit.getByRole('textbox', { name: 'Required answer phrases', exact: true }).fill('60 days');
  await edit.getByRole('button', { name: 'Save test question', exact: true }).click();
  await expect(caseCard.getByText('Expected: 60 days · accuracy-refunds.txt', { exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await caseCard.getByRole('button', { name: 'Delete test question', exact: true }).click();
  await expect(caseCard).toHaveCount(0);
  await page.getByRole('button', { name: 'View Baseline', exact: true }).click();
  const detail = page.getByRole('region', { name: 'Saved run results', exact: true });
  await expect(detail.getByText('Expected: 30 days · accuracy-refunds.txt', { exact: true })).toBeVisible();
  expect((await page.request.post('/api/backend/_test/accuracy/pause')).ok()).toBeTruthy();
  await start.getByRole('textbox', { name: 'Run name', exact: true }).fill('Cancelled check');
  await start.getByLabel('I approve the model calls for these selected questions.', { exact: true }).check();
  await start.getByRole('button', { name: 'Run selected questions', exact: true }).click();
  await expect(page.getByText('A run is active. Wait for it to finish or cancel the remaining questions.', { exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Cancel active run', exact: true }).click();
  await expect(detail.getByText('Cancelled · 0 of 1 questions finished', { exact: true })).toBeVisible();
  expect((await login('accuracy-viewer@example.com')).ok()).toBeTruthy(); await page.goto('/dashboard/analytics/accuracy');
  await expect(page.getByRole('heading', { name: 'Run history', exact: true })).toBeVisible();
  await expect(page.getByRole('form', { name: 'Run selected questions', exact: true })).toHaveCount(0);
  await expect(page.getByText('Add or edit test questions', { exact: true })).toHaveCount(0);
  expect((await page.request.post('/api/backend/evals/run', { data: {}, headers: { 'X-CSRF-Token': (await page.context().cookies()).find(c => c.name === 'chatbot_csrf')!.value } })).status()).toBe(403);
});
