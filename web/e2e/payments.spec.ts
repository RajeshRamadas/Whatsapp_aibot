import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('payments: test merchant, approve exact due, send link, verify captured webhook and restrict roles', async ({ page }) => {
  test.setTimeout(90000);
  const login = (email: string) => page.request.post('/api/backend/auth/login', { data: { email, password: 'payment-browser-passphrase' } });
  expect((await login('payments@example.com')).ok()).toBeTruthy();
  await page.goto('/dashboard/payments');
  await expect(page.getByText('No approved customer dues yet.')).toBeVisible();
  await page.getByText('Merchant Razorpay account', { exact: true }).click();
  await page.getByRole('textbox', { name: 'Merchant label', exact: true }).fill('Demo merchant');
  await page.getByLabel('Merchant key ID', { exact: true }).fill('rzp_test_browser1234');
  await page.getByLabel('Merchant key secret', { exact: true }).fill('browser-merchant-secret');
  await page.getByLabel('Merchant webhook secret', { exact: true }).fill('browser-payment-webhook-secret');
  await page.getByRole('button', { name: 'Save merchant connection', exact: true }).click();
  await expect(page.getByLabel('Merchant key secret', { exact: true })).toHaveValue('');
  await page.getByRole('button', { name: 'Test merchant connection', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Demo merchant · Connected · Test mode', exact: true })).toBeVisible();
  const form = page.getByRole('form', { name: 'Approve customer due', exact: true });
  await form.getByRole('combobox', { name: 'Merchant account', exact: true }).selectOption({ label: 'Demo merchant · Test mode' });
  await form.getByRole('combobox', { name: 'Customer conversation', exact: true }).selectOption({ index: 1 });
  await form.getByLabel('Amount (INR)', { exact: true }).fill('1250.50');
  await form.getByLabel('Payment purpose', { exact: true }).fill('Booking deposit');
  await form.getByLabel('Customer name', { exact: true }).fill('Demo customer');
  await form.getByLabel('International phone number', { exact: true }).fill('+919999000001');
  await form.getByRole('button', { name: 'Approve customer due', exact: true }).click();
  await expect(form.getByLabel('International phone number', { exact: true })).toHaveValue('');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Send approved payment link', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Open payment link', exact: true })).toHaveAttribute('href', 'https://rzp.io/i/browser-demo');
  const rows = await (await page.request.get('/api/backend/payments/requests')).json();
  expect(rows[0].amount).toBe(125050);
  expect((await page.request.post('/api/backend/_test/payments/' + rows[0].id + '/paid')).ok()).toBeTruthy();
  await page.getByRole('button', { name: 'Refresh payments', exact: true }).click();
  await expect(page.getByText('Verified payment reference: pay_browser123', { exact: true })).toBeVisible();
  const messages = await (await page.request.get('/api/backend/conversations/' + rows[0].conversation_id + '/messages')).json();
  expect(messages.some((m: { content: string }) => m.content.includes('Payment received: INR 1250.50'))).toBe(true);
  await page.getByRole('button', { name: 'हिन्दी', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'ग्राहक भुगतान', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByText('Merchant Razorpay account', { exact: true }).click();
  await page.setViewportSize({ width: 1280, height: 1100 });
  await page.mouse.move(0, 0);
  await page.screenshot({ path: '../docs/screenshots/t9-10-payments.png', fullPage: true });
  expect((await login('payment-agent@example.com')).ok()).toBeTruthy(); await page.goto('/dashboard/payments');
  await expect(page.getByRole('form', { name: 'Approve customer due', exact: true })).toBeVisible();
  await expect(page.getByText('Merchant Razorpay account', { exact: true })).toHaveCount(0);
  expect((await page.request.get('/api/backend/payments/connections')).status()).toBe(403);
  expect((await login('payment-reader@example.com')).ok()).toBeTruthy(); await page.goto('/dashboard/payments');
  await expect(page.getByText('Only owners, admins and agents can access customer payments.')).toBeVisible();
});
